"""Story flag cross-reference from the script listings (extract.py stage `scripts`): for every flag id, which
scripts (and which function in them) set it, clear it, check it or read its value. Read-only over
extracted/scripts/; the extractor writes the result (see extract.py `cmd_flagxref`). docs/engine/flags.md.

Native semantics (verified, proposed-names.md): std078_flagSetFalse WRITES 1 (sets), std079_flagSetTrue WRITES 0
(clears); std081_flagCheckTrue tests, std082_flagGetValue reads a multi-bit value."""
import os
import re
from collections import defaultdict

KINDS = {"std078_flagSetFalse": "set", "std079_flagSetTrue": "clear", "std081_flagCheckTrue": "check",
         "std082_flagGetValue": "read"}
CALL = re.compile(r"\b(std078_flagSetFalse|std079_flagSetTrue|std081_flagCheckTrue|std082_flagGetValue)\((\d+)")
FUNC = re.compile(r"^(func\d+):")


def scan(scripts_dir):
    """-> {flag id: {kind: set of 'area/script:function'}}, plus the number of calls with a non-literal id."""
    xref = defaultdict(lambda: defaultdict(set))
    dynamic = 0
    for area in sorted(os.listdir(scripts_dir)):
        adir = os.path.join(scripts_dir, area)
        if not os.path.isdir(adir):
            continue
        for name in sorted(os.listdir(adir)):
            if not name.endswith(".txt"):
                continue
            where = f"{area}/{name[:-4]}"
            func = "func0"
            for line in open(os.path.join(adir, name), encoding="utf-8", errors="replace"):
                m = FUNC.match(line)
                if m:
                    func = m.group(1)
                    continue
                for native, fid in CALL.findall(line):
                    xref[int(fid)][KINDS[native]].add(f"{where}:{func}")
                dynamic += len(re.findall(r"\b(?:std07[89]_flagSet\w+|std08[12]_flag\w+)\((?!\d)", line))
    return xref, dynamic


def text(xref, dynamic):
    out = ["# Story flag cross-reference (generated by tools/local/colo/flagxref.py from the script listings)", "",
           f"{len(xref)} flag ids used with a literal id; {dynamic} calls use a computed id (not listed).",
           "Kinds: set = writes 1 (std078), clear = writes 0 (std079), check = tests (std081), read = value (std082).",
           "Places: area/archive__entry:function. Flags set or checked by game code (Shadow data, treasure) are not here.",
           ""]
    for fid in sorted(xref):
        out.append(f"## flag {fid}")
        for kind in ("set", "clear", "check", "read"):
            if xref[fid].get(kind):
                out.append(f"- {kind}: " + ", ".join(sorted(xref[fid][kind])))
        out.append("")
    return "\n".join(out)
