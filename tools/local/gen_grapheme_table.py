"""Print the grapheme-cluster property table for port/src/pc_grapheme_table.h (the project's build helper, 2026-11-16).

Why: OrrePort's 12-letter name limit counts visible letters (snatcherLeo, 2026-11-16, the decision log): Unicode's extended
grapheme clusters (UAX #29). The rules need each character's Grapheme_Cluster_Break class, whether it is
Extended_Pictographic, and its Indic_Conjunct_Break value. No library is added for that (port/src/pc_grapheme.cpp says
why); this script builds a small range table from Unicode's own data files that the build already fetched:
  - SheenBidi's copy of the Unicode 17.0 database (build-pc/_deps/orre_sheenbidi-src/Tools/Unicode/):
    UnicodeData.txt (general categories, Hangul jamo names), DerivedCoreProperties.txt (Grapheme_Extend,
    Default_Ignorable_Code_Point, Indic_Conjunct_Break), PropList.txt (Prepended_Concatenation_Mark);
  - HarfBuzz's packed Extended_Pictographic table (build-pc/_deps/orre_harfbuzz-src/src/hb-unicode-emoji-table.hh,
    generated by HarfBuzz from emoji-data.txt 18.0), read back by evaluating its lookup for every code point.
GraphemeBreakProperty.txt itself isn't among those files, so the classes are derived the way UAX #29's Table 2
defines them (each rule below cites it). Two inputs are lists typed in from UAX #29 (the SpacingMark exceptions and
the Indic_Syllabic_Category part of Prepend): labelled "likely" in pc_grapheme.cpp.

Output: C source on stdout. Copy it into port/src/pc_grapheme_table.h with the file-edit tools (the project rules: generated
text never goes into the repo through the shell).
Usage (repo root): python -I tools/local/gen_grapheme_table.py [build dir, default build-pc] > <scratch file>
Platforms: any Python 3; the output is plain C, the same on every OS. XD: the same table (port code, no game data).
"""
import re
import sys
from pathlib import Path

if "--help" in sys.argv or "-h" in sys.argv:
    print(__doc__)
    sys.exit(0)

build = Path(sys.argv[1] if len(sys.argv) > 1 else "build-pc")
ucd = build / "_deps/orre_sheenbidi-src/Tools/Unicode"
emoji_hh = build / "_deps/orre_harfbuzz-src/src/hb-unicode-emoji-table.hh"
N = 0x110000

# the classes (pc_grapheme.cpp's enum): low 4 bits the Grapheme_Cluster_Break class, bit 4 Extended_Pictographic,
# bits 5-6 Indic_Conjunct_Break (1 Linker, 2 Consonant, 3 Extend)
OTHER, CR, LF, CONTROL, EXTEND, ZWJ, RI, PREPEND, SPACINGMARK, L, V, T = range(12)
EXTPICT = 0x10
INCB = {"Linker": 1 << 5, "Consonant": 2 << 5, "Extend": 3 << 5}


def ranges(path, prop=None):
    """(first, last, fields) for every data line of a UCD file, optionally only one property's lines"""
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        f = [x.strip() for x in line.split(";")]
        if prop is not None and f[1] != prop:
            continue
        a, _, b = f[0].partition("..")
        yield int(a, 16), int(b or a, 16), f


# general categories and names from UnicodeData.txt (its "<..., First>" / "<..., Last>" pairs are ranges)
gc = ["Cn"] * N
names = {}
first = None
for line in (ucd / "UnicodeData.txt").read_text(encoding="utf-8").splitlines():
    f = line.split(";")
    cp = int(f[0], 16)
    if f[1].endswith(", First>"):
        first = cp
        continue
    lo = first if f[1].endswith(", Last>") else cp
    first = None
    for c in range(lo, cp + 1):
        gc[c] = f[2]
    names[cp] = f[1]

grapheme_extend = [False] * N
default_ignorable = [False] * N
incb = [0] * N
for a, b, f in ranges(ucd / "DerivedCoreProperties.txt"):
    for c in range(a, b + 1):
        if f[1] == "Grapheme_Extend":
            grapheme_extend[c] = True
        elif f[1] == "Default_Ignorable_Code_Point":
            default_ignorable[c] = True
        elif f[1] == "InCB":
            incb[c] = INCB[f[2]]
pcm = [False] * N
for a, b, f in ranges(ucd / "PropList.txt", "Prepended_Concatenation_Mark"):
    for c in range(a, b + 1):
        pcm[c] = True

# Extended_Pictographic: HarfBuzz's packed table, evaluated as its _hb_emoji_is_Extended_Pictographic does
text = emoji_hh.read_text(encoding="utf-8")
m = re.search(r"_hb_emoji_u8\[(\d+)\]\s*=\s*\{([^}]*)\}", text)
u8 = [int(x) for x in m.group(2).replace("\n", " ").split(",") if x.strip()]
assert len(u8) == int(m.group(1))
look = re.search(r"_hb_emoji_is_Extended_Pictographic \(unsigned u\)\s*\{[^}]*return u<(\d+)u", text)
limit = int(look.group(1))
assert "packtab: [2^4,2^4,2^6]" in text and "_hb_emoji_u8+224u" in text and "_hb_emoji_u8[64u+" in text, \
    "HarfBuzz's emoji table changed shape: update the lookup below"


def b4(base, i):
    return (u8[base + (i >> 1)] >> ((i & 1) << 2)) & 15


def b1(base, i):
    return (u8[base + (i >> 3)] >> (i & 7)) & 1


def extpict(u):
    if u >= limit:
        return False
    return b1(224, (u8[64 + (b4(0, (u >> 6) >> 4) << 4) + ((u >> 6) & 15)] << 6) + (u & 63)) == 1


# UAX #29 Table 2's SpacingMark exceptions (Mc characters that are not SpacingMark), typed from the report
SPACING_EXCEPT = [(0x102B, 0x102C), (0x1038, 0x1038), (0x1062, 0x1064), (0x1067, 0x106D), (0x1083, 0x1083),
                  (0x1087, 0x108C), (0x108F, 0x108F), (0x109A, 0x109C), (0x1A61, 0x1A61), (0x1A63, 0x1A64),
                  (0xAA7B, 0xAA7B), (0xAA7D, 0xAA7D), (0x11720, 0x11721)]
# Prepend's Indic_Syllabic_Category part (Consonant_Preceding_Repha, Consonant_Prefixed): IndicSyllabicCategory.txt
# isn't among the fetched files, so the characters GraphemeBreakProperty.txt lists as Prepend (other than the
# Prepended_Concatenation_Marks, which come from PropList.txt) are typed in
PREPEND_ISC = [(0x0D4E, 0x0D4E), (0x111C2, 0x111C3), (0x1193F, 0x1193F), (0x11941, 0x11941), (0x11A3A, 0x11A3A),
               (0x11A84, 0x11A89), (0x11D46, 0x11D46), (0x11F02, 0x11F02), (0x113D1, 0x113D1)]


def inside(c, table):
    return any(a <= c <= b for a, b in table)


def gcb(c):
    """Grapheme_Cluster_Break by UAX #29 Table 2 (Hangul LV / LVT are computed in pc_grapheme.cpp)"""
    if c == 0x0D:
        return CR
    if c == 0x0A:
        return LF
    if c == 0x200D:
        return ZWJ
    if grapheme_extend[c] or 0x1F3FB <= c <= 0x1F3FF:  # Extend: Grapheme_Extend, or Emoji_Modifier
        return EXTEND
    if 0x1F1E6 <= c <= 0x1F1FF:
        return RI
    if pcm[c] or inside(c, PREPEND_ISC):
        return PREPEND
    # Control: Zl, Zp, Cc, Cf, or unassigned default-ignorable; not CR, LF, ZWNJ, ZWJ or a prepended mark
    if gc[c] in ("Zl", "Zp", "Cc", "Cf") or (gc[c] == "Cn" and default_ignorable[c]):
        if c not in (0x200C,):
            return CONTROL
    # SpacingMark: Mc that isn't Extend, less the exceptions, plus Thai / Lao SARA AM
    if c in (0x0E33, 0x0EB3) or (gc[c] == "Mc" and not inside(c, SPACING_EXCEPT)):
        return SPACINGMARK
    n = names.get(c, "")
    if n.startswith("HANGUL CHOSEONG"):
        return L
    if n.startswith("HANGUL JUNGSEONG"):
        return V
    if n.startswith("HANGUL JONGSEONG"):
        return T
    return OTHER


vals = []
for c in range(N):
    if 0xD800 <= c <= 0xDFFF:
        vals.append(CONTROL)  # surrogates (Cs): never in a name, a break either side
        continue
    vals.append(gcb(c) | (EXTPICT if extpict(c) else 0) | incb[c])

runs = []
c = 0
while c < N:
    v = vals[c]
    e = c
    while e + 1 < N and vals[e + 1] == v:
        e += 1
    if v != OTHER:
        runs.append((c, e, v))
    c = e + 1

print("/* generated by tools/local/gen_grapheme_table.py from Unicode 17.0 (SheenBidi's copy of the database) and")
print(" * HarfBuzz's Extended_Pictographic table (emoji-data 18.0); %d ranges, every other code point is Other */" % len(runs))
print("static const PcGraphemeRange kGraphemeRanges[%d] = {" % len(runs))
line = "   "
for a, b, v in runs:
    item = " {0x%X, 0x%X, 0x%02X}," % (a, b, v)
    if len(line) + len(item) > 118:
        print(line)
        line = "   "
    line += item
print(line)
print("};")
