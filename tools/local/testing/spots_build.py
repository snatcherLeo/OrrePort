"""Build docs/testing/spots.json, the quick-jump list for the PC debug menu (B's F1 menu; snatcherLeo approved 2026-10-17).

    python -I tools/local/testing/spots_build.py [route.json] [spots.json]

One spot per story-route step, read from route.json (no disc access): where to warp (room id, entry point) and the
story flags to set / clear so the room shows that point of the story. Fields of each spot:
- id: stable key ("step-6"); name: a short label (hand names for key spots below, else "step N: <room>");
- route_step, room_id, room (archive name), entry (the position-point index the warp lands on);
- entry_known: true when the entry comes from a real exit into the room (route.json room_graph), false when it is a
  default (0, or the first exit found) and the player may land somewhere odd;
- flags_set: every flag the main-path steps before this one set (their story-chain flags) plus the step's own
  requirements; flags_clear: the step's "must be clear" flags. Story flags only: variables (money, party, items) are
  not covered, so a spot is "likely" right, not verified, until a jump is checked in the game;
- battle: the battle ids this step starts (for "jump to the battle" spots), or [].
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROUTE = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "..", "docs", "testing", "route.json")
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(ROUTE), "spots.json")

# readable names for the spots people will jump to most (our words); the rest are "step N: <room>"
NAMES = {2: "Outskirt Stand: arrival", 4: "Outskirt Stand: diner", 6: "Outskirt Stand: Willie's battle",
         7: "Phenac City: arrival", 9: "Phenac City: the sack (Rui joins)", 11: "Phenac City: the mayor's house",
         12: "Phenac Stadium: reception"}


def main():
    with open(ROUTE, encoding="utf-8") as f:
        route = json.load(f)
    exits = route["room_graph"]["exits"]
    spots, set_before, prev_room = [], [], None
    for s in route["steps"]:
        room = s.get("room") or {}
        rid, arch = room.get("id"), room.get("archive")
        if rid is None:  # no room (e.g. the ending): nothing to warp to
            set_before += [fl["id"] for fl in s.get("flags", [])]
            continue
        into = [e for e in exits if e["to"] == rid]
        from_prev = [e for e in into if e["from"] == prev_room]
        if rid == prev_room and spots:  # same room as the step before: stay where that spot lands
            entry, known = spots[-1]["entry"], spots[-1]["entry_known"]
        elif from_prev:
            entry, known = from_prev[0]["entry"], True
        elif into:
            entry, known = into[0]["entry"], False
        else:
            entry, known = 0, False
        req = s.get("requires") or {}
        flags_set = sorted(set(set_before) | set(req.get("flags_set", [])) - set(req.get("flags_clear", [])))
        spots.append({"id": f"step-{s['step']}", "name": NAMES.get(s["step"], f"step {s['step']}: {arch}"),
                      "route_step": s["step"], "room_id": rid, "room": arch, "entry": entry, "entry_known": known,
                      "flags_set": flags_set, "flags_clear": sorted(req.get("flags_clear", [])),
                      "battle": [b["id"] for b in (s.get("battle") or [])]})
        if s.get("main_path", not s.get("optional")):
            set_before += [fl["id"] for fl in s.get("flags", [])]
        prev_room = rid
    out = {"about": "Quick-jump spots for the PC debug menu, one per story-route step; generated by "
                    "tools/local/testing/spots_build.py from route.json. Story flags only (variables not covered): "
                    "each spot is likely right until a jump is checked in the game.",
           "fields": {"id": "stable key", "name": "menu label", "route_step": "route.json step",
                      "room_id": "warp target room id", "room": "room archive name",
                      "entry": "position-point index to land on", "entry_known": "false = default entry",
                      "flags_set": "story flags to set", "flags_clear": "story flags to clear",
                      "battle": "battle ids this step starts"},
           "spots": spots}
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(OUT, len(spots), "spots,", sum(1 for s in spots if s["entry_known"]), "with a known entry")


if __name__ == "__main__":
    main()
