"""Turn a recorded Dolphin pad log into a PC pad script (testing lane).

    python -I tools/local/testing/pad_to_script.py <walk_pad.jsonl> <out.pad> [--prefix "<steps>"] [--start-offset 900]

The log comes from dolphin_walk.py (one JSON line per pad change: frame, room, frames since that room was first seen,
the whole pad). The output is the project's ORRE_PAD_SCRIPT file format (port/src/pc_pad_script.c; use it as
ORRE_PAD_SCRIPT=@file:<out.pad>): each step WHEN:WHAT sets the whole pad.
- WHEN: "@R+N" = N frames after room R is entered (the first entry at or after the previous step), so the PC's own load
  times don't shift the inputs; the first stretch in room 1 is offset by --start-offset (the Dolphin walk starts from
  the s1_out_arrival state, 900 frames after Outskirt Stand loads). Steps logged while the room id reads "none"
  (0xFFFFFFFF, after a battle) become "+N" after the previous step.
- WHAT: Dolphin's StickX / StickY -> SX= / SY=; A, B, Start, Up, Down, Left, Right -> A B START UP DOWN LEFT RIGHT; an
  empty pad -> "-".
--prefix puts fixed steps in front (e.g. the new-game menu inputs of routes.py's new_game route).
"""
import argparse, json

NAMES = {"A": "A", "B": "B", "X": "X", "Y": "Y", "Z": "Z", "L": "L", "R": "R", "Start": "START",
         "Up": "UP", "Down": "DOWN", "Left": "LEFT", "Right": "RIGHT"}


def what(pad):
    toks = []
    for k, v in pad.items():
        if k == "StickX":
            toks.append(f"SX={int(v)}")
        elif k == "StickY":
            toks.append(f"SY={int(v)}")
        elif v and k in NAMES:
            toks.append(NAMES[k])
    return "+".join(toks) if toks else "-"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("log"); ap.add_argument("out")
    ap.add_argument("--events", help="the walk's walk.jsonl (room entries); default: next to the pad log")
    ap.add_argument("--prefix", default="")
    ap.add_argument("--start-offset", type=int, default=900)
    a = ap.parse_args()
    rows = [json.loads(l) for l in open(a.log, encoding="utf-8") if l.strip()]
    lines = ["# generated by tools/local/testing/pad_to_script.py from " + a.log.replace("\\", "/").split("/")[-1]]
    if a.prefix:
        lines += [s.strip() for s in a.prefix.split(",") if s.strip()]
    import os
    ev_path = a.events or os.path.join(os.path.dirname(a.log), "walk.jsonl")
    entries = [(e["frame"], e["room"]) for e in (json.loads(l) for l in open(ev_path, encoding="utf-8") if l.strip())
               if e.get("ev") == "room"]
    prev_frame = None
    for r in rows:
        ent = [e for e in entries if e[0] <= r["frame"]]
        ent_frame, room = ent[-1] if ent else (r["frame"], r["room"])
        since = r["frame"] - ent_frame
        if room == 0xFFFFFFFF or room is None:
            when = f"+{r['frame'] - prev_frame}" if prev_frame is not None else f"+{since}"
        else:
            if ent and ent[-1] == entries[0]:
                since += a.start_offset          # the walk starts from a state taken start_offset frames into this room
            when = f"@{hex(room)}+{since}"
        lines.append(f"{when}:{what(r['pad'])}")
        prev_frame = r["frame"]
    open(a.out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(a.out, len(lines) - 1, "steps")


if __name__ == "__main__":
    main()
