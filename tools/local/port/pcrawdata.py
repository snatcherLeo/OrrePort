"""Leave the data units' raw tables out of the PC build; pcdata.py generates them instead (OrrePort first link).

The data units (src/game/data/*.c) define much of the game's data as raw tables standing in for unknown layouts:
`u8 lbl_802CF810[74976] = {...}` (bytes in GameCube byte order) and `void* lbl_8027A500[68440] = {...}` (32-bit words,
many of them addresses). Compiled on the PC they are wrong: the bytes are big-endian where the C reads native
integers, and a void* is 8 bytes, so every word table doubles in size and every offset into it breaks.
pcdata.py already generates PC-correct definitions from the original objects (typed fields converted, pointer words
relocated, unclear data kept raw and listed); it skips symbols the C defines.

This tool wraps every raw array definition in a data unit (element type u8 / s8 / char / u16 / s16 / u32 / s32 /
void*), and the `extern u8 Function[];` declarations (function addresses) of functions that have a canonical prototype on
the PC (include/pc/prototypes.h; the u8[] view would clash with it), in
`#ifndef TARGET_PC ... #endif`. pcdata.py then treats them as not defined in C. Typed definitions (floats, named
structs) stay compiled on the PC. The GameCube build is unchanged (data units don't use __LINE__; verify with the
full build, 26 SHA-1 and fullsnap). Idempotent.

Usage (repo root): python -I tools/local/port/pcrawdata.py [--dry]
"""
import re
import sys
from pathlib import Path

RAW = {"u8", "s8", "char", "unsigned char", "u16", "s16", "u32", "s32", "void*", "void *"}
TAG = "#ifndef TARGET_PC /* PC: raw table, generated by tools/local/port/pcdata.py (pcrawdata.py) */"
DEF = re.compile(r"^(?:static\s+)?(?:const\s+)?([A-Za-z_][\w\s\*]*?)\s*\b(lbl_[0-9A-Fa-f]{8})\s*\[")
FUNC_EXTERN = re.compile(r"^extern\s+u8\s+(?!lbl_)([A-Za-z_]\w*)\s*\[\s*\]\s*;")


# --scalars NAME,NAME,...: also leave out these one-line scalar definitions (`u32 lbl_80478AC0 = 0x20;`), for variables
# the PC must take from pcdata.py with their PC types (2026-10-18: upstream's new data units define variables the PC
# build generated before, among them pointers stored as u32 / u8[4], which are 8 bytes on the PC)
SCALAR = re.compile(r"^(?:static\s+)?(?:const\s+)?[A-Za-z_][\w\s\*]*?\b([A-Za-z_]\w*)\s*(?:=[^;]*)?;\s*(?:/\*.*\*/)?\s*$")
SCALARS = set(sys.argv[sys.argv.index("--scalars") + 1].split(",")) if "--scalars" in sys.argv else set()


# --bare FILE,FILE,...: in these units, wrap without the `#else extern T name[];` view (2026-10-18: small .bss / .sbss /
# .sdata variables, many of them pointers stored as u32 / u8[4] on the GameCube; a u8[] view on the PC makes pcdata.py
# generate them with their GameCube size, 4 bytes, so a pointer stored there loses its upper half)
BARE = set(sys.argv[sys.argv.index("--bare") + 1].split(",")) if "--bare" in sys.argv else set()
BARE_NOW = [False]


CANONICAL = set(re.findall(r"\b([A-Za-z_]\w*)\s*\(", Path("include/pc/prototypes.h").read_text(encoding="utf-8")))


def wrap(text):
    nl = "\r\n" if "\r\n" in text else "\n"
    L = text.split(nl)
    out, i, n_def, n_ext = [], 0, 0, 0
    while i < len(L):
        line = L[i]
        prev = out[-1] if out else ""
        if prev.startswith("#ifndef TARGET_PC"):
            out.append(line)
            i += 1
            continue
        m = DEF.match(line)
        if m and " ".join(m.group(1).split()) in RAW:
            # extent: to the line ending the initializer (`};`) or the declaration (`;`)
            j = i
            if "=" in line:
                depth = 0
                while j < len(L):
                    depth += L[j].count("{") - L[j].count("}")
                    if depth <= 0 and L[j].rstrip().endswith(";"):
                        break
                    j += 1
            else:
                while j < len(L) and not L[j].rstrip().endswith(";"):
                    j += 1
            ty = " ".join(m.group(1).split())
            if BARE_NOW[0]:  # --bare: no u8[] view on the PC, so pcdata.py infers the PC type itself (pointers: 8 bytes)
                out += [TAG] + L[i:j + 1] + ["#endif"]
            else:
                out += [TAG] + L[i:j + 1] + ["#else", f"extern {ty} {m.group(2)}[]; /* generated by pcdata.py */",
                                              "#endif"]
            n_def += 1
            i = j + 1
            continue
        sm = SCALAR.match(line)
        if sm and sm.group(1) in SCALARS:  # --scalars: a one-line variable pcdata.py generates with its PC type
            out += [TAG, line, "#endif"]
            n_def += 1
            i += 1
            continue
        fm = FUNC_EXTERN.match(line)
        if fm and fm.group(1) in CANONICAL:  # only where the canonical prototype would clash with the u8[] view
            out += [TAG, line, "#endif"]
            n_ext += 1
            i += 1
            continue
        out.append(line)
        i += 1
    return nl.join(out), n_def, n_ext


def main():
    tot_d = tot_e = files = 0
    for p in sorted(Path("src/game/data").glob("*.c")):
        b = p.read_bytes().decode("utf-8", errors="surrogateescape")
        BARE_NOW[0] = p.as_posix() in BARE or p.name in BARE
        new, d, e = wrap(b)
        if d or e:
            files += 1
            tot_d += d
            tot_e += e
            if "--dry" not in sys.argv:
                p.write_bytes(new.encode("utf-8", errors="surrogateescape"))
    print(f"{files} data units: {tot_d} raw tables and {tot_e} function-address externs left out on the PC")
    return 0


if __name__ == "__main__":
    sys.exit(main())
