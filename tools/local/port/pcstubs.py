"""Generate logging stubs for every function the PC link can't find (OrrePort; the port's own to-do list).

When the PC build links the game, every function that has no definition (no C yet, or an SDK call Aurora doesn't
provide) is an "undefined reference". This tool turns that list into a C file of stubs. Each stub, the first time it
is called, logs one line

    missing function #<n>: <name> called from <caller address> (<return kind>)

to stderr and to `missing_functions.log` (in the current directory: the portable OrrePort folder), then returns 0
(0.0 for functions whose canonical prototype returns f32 / f64, nothing for void). Later calls stay silent. So running
the port produces the list of missing functions **in the order the game needs them**. Caller addresses are host
addresses; resolve them with `addr2line -f -e orreport.exe <address>` (the exe is linked at a fixed base, no ASLR) or
with `--resolve` below.

Return types come from `include/pc/prototypes.h` where the function has a canonical prototype; otherwise the stub
returns an integer (safe for integer and pointer returns; a float-returning function without a canonical prototype
would get garbage: give it a prototype first, the tool lists such names as "unknown return type").

Data symbols (`lbl_...` variables) can't be stubbed this way: they are listed separately ("undefined data").

Usage:
  python -I tools/local/port/pcstubs.py LINK_ERRORS.txt [-o build-pc/generated/pc_missing_stubs.c]
      LINK_ERRORS.txt: the linker's output (lines containing "undefined reference to `name'"), or one name per line.
  python -I tools/local/port/pcstubs.py --resolve missing_functions.log orreport.exe
      adds the caller's function name to each log line (uses addr2line from MSYS2).
"""
import re
import subprocess
import sys
from pathlib import Path

PROTO = Path("include/pc/prototypes.h")


def canonical_returns():
    """name -> return type text, from the canonical prototypes."""
    out = {}
    if PROTO.exists():
        for line in PROTO.read_text(encoding="utf-8").splitlines():
            m = re.match(r"^\s*(?:extern\s+)?([\w\s\*]+?)\s*\b(\w+)\s*\(", line)
            if m and not line.lstrip().startswith(("#", "/*", "*", "typedef", "struct")):
                out[m.group(2)] = " ".join(m.group(1).split())
    return out


def undefined_names(text):
    names = re.findall(r"undefined reference to `([^'`]+)'", text)
    if not names:  # one name per line
        names = [l.strip() for l in text.splitlines() if re.fullmatch(r"[A-Za-z_]\w*", l.strip())]
    seen, out = set(), []
    for n in names:
        if n not in seen:
            seen.add(n)
            out.append(n)
    return out


def is_data(name):
    return name.startswith(("lbl_", "jumptable_", "@")) or name.startswith("__") and name.endswith("__")


HEADER = r'''/* Generated by tools/local/port/pcstubs.py: logging stubs for functions the PC link could not find.
 * Do not edit; regenerate. Each stub logs its first call (name, caller) and returns 0 / 0.0 / nothing. */
#include <stdio.h>
#include <stdint.h>

static int pc_missing_count;

static void pc_missing(const char* name, const char* kind, void* caller)
{
    FILE* f = fopen("missing_functions.log", "a");
    ++pc_missing_count;
    fprintf(stderr, "missing function #%d: %s called from 0x%llx (%s)\n", pc_missing_count, name,
            (unsigned long long)(uintptr_t)caller, kind);
    if (f != NULL) {
        fprintf(f, "missing function #%d: %s called from 0x%llx (%s)\n", pc_missing_count, name,
                (unsigned long long)(uintptr_t)caller, kind);
        fclose(f);
    }
}

#define PC_STUB_PROLOGUE(name, kind) \
    static int logged; \
    if (!logged) { logged = 1; pc_missing(name, kind, __builtin_return_address(0)); }

'''


def stub(name, ret):
    if ret is None:
        return (f"/* unknown return type: integer stub */\n"
                f"uintptr_t {name}() {{ PC_STUB_PROLOGUE(\"{name}\", \"unknown return type\") return 0; }}\n")
    r = ret.replace("const ", "").strip()
    if r == "void":
        return f"void {name}() {{ PC_STUB_PROLOGUE(\"{name}\", \"void\") }}\n"
    if r in ("f32", "float"):
        return f"float {name}() {{ PC_STUB_PROLOGUE(\"{name}\", \"returns f32\") return 0.0f; }}\n"
    if r in ("f64", "double"):
        return f"double {name}() {{ PC_STUB_PROLOGUE(\"{name}\", \"returns f64\") return 0.0; }}\n"
    return (f"uintptr_t {name}() {{ PC_STUB_PROLOGUE(\"{name}\", \"returns {r}\") return 0; }}\n")


def generate(link_text, out_path):
    rets = canonical_returns()
    names = undefined_names(link_text)
    funcs = [n for n in names if not is_data(n)]
    data = [n for n in names if is_data(n)]
    unknown = [n for n in funcs if n not in rets]
    body = HEADER + "".join(stub(n, rets.get(n)) for n in funcs)
    if data:
        body += "\n/* Undefined data (not stubbed; needs the game's data sections):\n" + \
                "".join(f" *   {n}\n" for n in data) + " */\n"
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body, encoding="utf-8")
    print(f"{len(funcs)} function stubs ({len(unknown)} with unknown return type), {len(data)} undefined data symbols -> {out}")
    if unknown:
        print("unknown return type (give these a canonical prototype): " + ", ".join(unknown[:30]) +
              (" ..." if len(unknown) > 30 else ""))


def resolve(log_path, exe):
    lines = Path(log_path).read_text(encoding="utf-8").splitlines()
    addrs = [re.search(r"called from (0x[0-9a-fA-F]+)", l) for l in lines]
    todo = [m.group(1) for m in addrs if m]
    names = {}
    if todo:
        r = subprocess.run(["addr2line", "-f", "-C", "-e", exe] + todo, capture_output=True, text=True)
        res = r.stdout.splitlines()
        for i, a in enumerate(todo):
            names[a] = (res[2 * i] if 2 * i < len(res) else "?")
    for l, m in zip(lines, addrs):
        print(l + (f" [in {names.get(m.group(1), '?')}]" if m else ""))


if __name__ == "__main__":
    if "--resolve" in sys.argv:
        i = sys.argv.index("--resolve")
        resolve(sys.argv[i + 1], sys.argv[i + 2])
    else:
        src = sys.argv[1]
        out = sys.argv[sys.argv.index("-o") + 1] if "-o" in sys.argv else "build-pc/generated/pc_missing_stubs.c"
        generate(Path(src).read_text(encoding="utf-8", errors="replace"), out)
