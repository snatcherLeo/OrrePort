"""Address names -> real names for the PC link (OrrePort; first link).

Game code often calls a function by its address name (`fn_8001D834(...)`) after symbols.txt renamed it
(`menuSubCalcColor`). On the GameCube the linker resolves both through dtk's symbol map; the PC linker only sees the
C names, so every such call would be an undefined symbol. This writes include/pc/game_pc_alias.h: one
`#define fn_<address> <name>` for every address name called in src/ whose function has a real name in symbols.txt and
no alias yet (B's port/src/sdk_pc_alias.h covers the SDK; a file's own `#define fn_X name` lines win, since they come
after the force-included header and redefine nothing different). Only used on the PC (force-included by the PC
build and pc_probe). Re-run after symbols.txt changes.

Usage (repo root): python -I tools/local/port/gamealias.py
"""
import re
from pathlib import Path

OUT = Path("include/pc/game_pc_alias.h")


def main():
    sym = {}
    for line in open("config/GC6E01/symbols.txt", encoding="utf-8"):
        m = re.match(r"(\S+) = \.text:0x([0-9A-F]+);", line)
        if m:
            sym[m.group(2)] = m.group(1)
    used = set()
    for p in Path("src").rglob("*.c*"):
        used |= set(re.findall(r"\bfn_([0-9A-F]{8})\b", p.read_text(encoding="utf-8", errors="replace")))
    sdk = set()
    alias = Path("port/src/sdk_pc_alias.h")
    if alias.exists():
        sdk = set(re.findall(r"#\s*define\s+fn_([0-9A-F]{8})\b", alias.read_text(encoding="utf-8", errors="replace")))
        sdk |= set(re.findall(r"/\*\s*fn_([0-9A-F]{8}):", alias.read_text(encoding="utf-8", errors="replace")))
    rows = []
    for a in sorted(used):
        name = sym.get(a)
        if not name or name.startswith("fn_") or a in sdk or not re.match(r"^[A-Za-z_]\w*$", name):
            continue
        rows.append(f"#define fn_{a} {name}")
    head = ["/* Address names -> real names for the PC link (OrrePort). Generated by tools/local/port/gamealias.py from",
            " * config/GC6E01/symbols.txt; do not edit by hand. PC only: the GameCube build never includes it.",
            " * Game code calls these functions by address name; symbols.txt has renamed them, and only dtk's map links the",
            " * two on the GameCube. SDK functions are in port/src/sdk_pc_alias.h. */",
            "#ifndef PC_GAME_PC_ALIAS_H", "#define PC_GAME_PC_ALIAS_H", "#ifdef TARGET_PC"]
    OUT.write_text("\n".join(head + rows + ["#endif", "#endif", ""]), encoding="utf-8")
    print(f"{len(rows)} aliases -> {OUT}")


if __name__ == "__main__":
    main()
