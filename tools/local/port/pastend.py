"""Find data addressed past the end of its own symbol (OrrePort).

On the GameCube neighbouring data sits in one block, so the compiler (and our matching C) may reach a string or table
as `lbl_X + offset` with an offset beyond lbl_X's own size: the bytes really belong to the next symbol(s). On the PC
every symbol is its own array, so such an access reads unrelated memory (the floor readers' "scene_data" lookup,
gs_floor.c's messages: both fixed 2026-10-15/16). This lists, in src/game outside data/, every `lbl_X + 0xN` and
every local alias `name = (...)lbl_X;` later used as `name + 0xN`, for symbols the file declares as arrays, where
N >= lbl_X's size in symbols.txt, with the
symbol that really holds that address. Lines inside the `#else` branch of `#ifdef TARGET_PC` blocks are skipped, and
so are expressions already wrapped by a PC mapping macro (FLOOR_READ_STRING, FLOOR_MESSAGES).
Usage (repo root): python -I tools/local/port/pastend.py
"""
import bisect
import re
from pathlib import Path

syms = {}
table = []
for line in Path("config/GC6E01/symbols.txt").read_text(encoding="utf-8").splitlines():
    m = re.match(r"(lbl_[0-9A-F]{8}) = \.\w+:0x([0-9A-F]+); // type:object size:0x([0-9A-F]+)", line)
    if m:
        a, s = int(m.group(2), 16), int(m.group(3), 16)
        syms[m.group(1)] = (a, s)
        table.append((a, s, m.group(1)))
table.sort()
starts = [t[0] for t in table]


def holder(address):
    i = bisect.bisect_right(starts, address) - 1
    if i >= 0 and address < table[i][0] + table[i][1]:
        return f"{table[i][2]} + 0x{address - table[i][0]:X}"
    return "no symbol"


def live_lines(text):
    state = []
    for n, line in enumerate(text.splitlines(), 1):
        s = line.strip()
        if s.startswith("#if"):
            state.append("pc" if "TARGET_PC" in s and not s.startswith("#ifndef") else "other")
        elif s.startswith("#else") and state:
            state[-1] = "gc" if state[-1] == "pc" else state[-1]
        elif s.startswith("#endif") and state:
            state.pop()
        elif "gc" not in state:
            yield n, line


DIRECT = re.compile(r"\b(lbl_[0-9A-F]{8})\s*\+\s*(0x[0-9A-Fa-f]+|\d+)\b")  # byte offsets only (an index counts elements)
# a local set from a symbol, with or without a cast (`data = lbl_80266DC0;` was missed before 2026-10-16: the
# name-entry table read at +0x88 past a 12-byte symbol)
ALIAS = re.compile(r"\b(\w+)\s*=\s*(?:\([^;]*?\)\s*)?&?\s*(lbl_[0-9A-F]{8})\s*;")
WRAPPED = re.compile(r"FLOOR_READ_STRING|FLOOR_MESSAGES")
hits = []
for p in sorted(Path("src/game").rglob("*.c")):
    if p.parts[2] == "data":
        continue  # the data units' initializers: generated by pcdata.py on the PC
    text = p.read_text(errors="replace")
    # only symbols this file declares as arrays: `lbl_X + N` is then address arithmetic on lbl_X itself (for a pointer
    # variable it offsets what the pointer holds, which is fine)
    arrays = set(re.findall(r"\b(lbl_[0-9A-F]{8})\s*\[", text))
    # ... minus symbols the file declares as pointer variables (`extern u8* lbl_X;`): there `lbl_X[i]` and `lbl_X + N`
    # index what the pointer holds (the battle script pointer lbl_8047B610: 135 false hits before 2026-10-16)
    arrays -= set(re.findall(r"\*\s*(lbl_[0-9A-F]{8})\s*[;=,)]", text))
    aliases = {}
    for n, line in live_lines(text):
        for m in ALIAS.finditer(line):
            aliases[m.group(1)] = m.group(2)
        if WRAPPED.search(line):
            continue
        found = [(m.group(1), m.group(2)) for m in DIRECT.finditer(line)]
        for name, sym in aliases.items():
            found += [(sym, m.group(1)) for m in re.finditer(rf"\b{re.escape(name)}\s*\+\s*(0x[0-9A-Fa-f]+|\d+)\b", line)]
        for sym, off in found:
            if sym not in syms or sym not in arrays:
                continue
            a, s = syms[sym]
            o = int(off, 0)
            if o >= s:
                hits.append(f"{p.as_posix()}:{n}: {sym} (0x{s:X} bytes) + 0x{o:X} -> really {holder(a + o)}")
for h in hits:
    print(h)
print(f"{len(hits)} accesses past the end of their symbol")
