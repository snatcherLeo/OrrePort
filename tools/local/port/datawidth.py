"""Data read at a different width than the PC stores it: the "table written as u32, read as u16" bug family.

On the GameCube (big-endian) a table defined as u32 words and read as u16 halves gives the halves in written order; on
the little-endian PC each word's halves come out swapped. Likewise a table written as raw bytes in GameCube order and
read through a u16 / u32 cast gives byte-swapped values on the PC. Found 2026-10-18: Protect's success table (u32[2] read
as u16[4]: the first use read 7FFF instead of FFFF) and two byte lists filled by one u16 / u32 store (golden-slice M31).

What matters is how the PC stores each symbol, which is not always the C definition:
  - a definition inside `#ifdef TARGET_PC` is the PC's own (hand-fixed): reported as handled;
  - a raw table the PC build leaves out (`#ifndef TARGET_PC /* PC: raw table ...` in the data units, pcrawdata.py) is
    generated by pcdata.py from the disc bytes: its PC form is read from build-pc/generated/pc_data_main.c (typed and
    converted to native order, a record of typed fields, or raw big-endian bytes when pcdata was unsure);
  - data in a pcfixed.txt raw range with no PC copy sits at its GameCube address as raw big-endian bytes;
  - anything else is compiled from its C definition: a u8 table written in GameCube byte order stays in that order.
Each read of the symbol in the src/game and src/hsd files the PC compiles (build-pc/firstlink/compiled.txt plus the .c
files they include; GameCube-only `#ifndef TARGET_PC` / `#else` branches skipped; src/musyx is replaced by musyx-pc) is
then classified:
  - a cast `(T*)lbl_X` / `(T*)(lbl_X + n)`, an `extern T lbl_X` declaration the file reads by value (indexes the array,
    uses the scalar), or a wide store `*(u16*)p = lbl_X`: a native read at T's width ("addr": a declaration only used
    for its address);
  - a struct view (`extern S lbl_X`, `(S*)lbl_X`): a native read at S's field widths (parsed from the sources; a
    DISC_STRUCT type reads big-endian);
  - a read through `DISC_U16(...)` / `DISC_U32(...)` / other `DISC_*` accessors (the label as the accessor's base): a
    big-endian read.
Verdicts:
  BUG    a native wide read of bytes stored in GameCube order (raw / byte table), a native read at a width that differs
         from a typed PC table's element width (cast reads), or a big-endian read of a natively converted table;
  CHECK  a declaration-only view at another width (often just an address passed on, or a whole-table copy), mixed read
         widths on one symbol (a copy at one width then reads at another), or a record read at a width none of its
         fields has: read the code;
  ok     the reads match the PC storage (listed with --all).
Symbols whose GameCube definition is all zero are skipped (no byte order), unless --all.

Usage: python -I tools/local/port/datawidth.py [--all] [--generated PATH/pc_data_main.c] [--compiled PATH/compiled.txt]
  Both default to this checkout's build-pc/ files, or the main checkout's when run from a worktree kept in a
  `worktrees` folder inside it. Without them, generated symbols are judged by their GameCube definition (marked) and every file
  counts as compiled. Run it after a PC build (the generated data is what it checks).
Limits: reads at computed offsets through local pointers (`data + 0x78`) are not followed; a local typedef that shares
its name with another struct is read with the first layout found; a raw table whose wide fields are all zero is a
false positive (zero reads the same both ways).
Output: a report on stdout. Reads sources only; writes nothing. Colosseum-specific paths; the method is reusable.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
# src/musyx is not compiled for the PC (extern/musyx-pc replaces it), so its reads don't count (2026-10-18)
SRC = [ROOT / "src" / "game", ROOT / "src" / "hsd"]
WIDTH = {"u8": 1, "s8": 1, "char": 1, "u16": 2, "s16": 2, "u32": 4, "s32": 4, "f32": 4, "f64": 8, "u64": 8, "s64": 8,
         "BOOL": 4, "int": 4, "short": 2, "float": 4, "double": 8, "void*": 4}
TYPES = "|".join(sorted((t for t in WIDTH if not t.endswith("*")), key=len, reverse=True))
DEF_RE = re.compile(r"^(?!\s*extern)[^;()]*?\b(" + TYPES + r")\s+(lbl_[0-9A-F]{8})\s*(\[[^\]]*\])?\s*=\s*([^;]*);", re.M | re.S)
DECL_RE = re.compile(r"\bextern\s+(?:const\s+|volatile\s+)*(" + TYPES + r")\s+(lbl_[0-9A-F]{8})\b")
CAST_RE = re.compile(r"\(\s*(?:const\s+|volatile\s+)*(" + TYPES + r")\s*\*\s*\)\s*(?:\(\s*)?&?\s*(lbl_[0-9A-F]{8})\b")
STORE_RE = re.compile(r"\*\s*\(\s*(u16|s16|u32|s32)\s*\*\s*\)\s*\(?\s*\w+\s*\)?\s*=\s*(?:\(\s*\w+\s*\)\s*)?(lbl_[0-9A-F]{8})\s*;")
DISC_RE = re.compile(r"\bDISC_(?:U16|S16|U32|S32|F32|EL_S16|EL_F32|EL_SET16|STORE16|STORE32|STORE_F32)\s*\(")
GEN_RE = re.compile(r"^(?!extern|static|typedef)(struct\s*\{([^}]*)\}|[A-Za-z_]\w*\s*\**)\s*(lbl_[0-9A-F]{8})\b[^\n]*", re.M)
BYTE = {"u8", "s8", "char", "unsigned char"}
GEN_W = dict(WIDTH, **{"unsigned char": 1, "unsigned short": 2, "unsigned int": 4})
# views through a named struct type: `extern [const] T lbl_X` / `(const T*)lbl_X` with T not a scalar type
SDECL_RE = re.compile(r"\bextern\s+(?:const\s+|volatile\s+)*(?:struct\s+)?([A-Za-z_]\w*)\s+(lbl_[0-9A-F]{8})\b")
SCAST_RE = re.compile(r"\(\s*(?:const\s+|volatile\s+)*(?:struct\s+)?([A-Za-z_]\w*)\s*\*\s*\)\s*(?:\(\s*)?&?\s*(lbl_[0-9A-F]{8})\b")
NOT_STRUCT = set(WIDTH) | BYTE | {"void", "const", "volatile", "unsigned", "signed", "long"}
# Findings read and judged correct (2026-10-18 triage, golden-slice M33): shown as "triaged" (with --all), not BUG / CHECK.
# Re-check an entry when its readers or its pcdata_types.txt line change.
TRIAGED = {
    "lbl_80266678": "pcdata `bytes`: copied in u32 / u16 pieces into a byte buffer, then read by byte",
    "fight_waza_hit_kakuritu_data": "pcdata `bytes`: {numerator, denominator} byte pairs read through a u16 pointer",
    "lbl_80279FE0": "u16[11] copied in u32 pieces, then read as u16: the copy keeps the bytes",
    "lbl_80266E18": "the 16 bytes after the two records stay raw: menuNameEntry_exact_80028FBC.c reads them with DISC_S32",
    "lbl_8035B818": "event log: every wide field is zero in the data, and the game writes and reads it natively",
    "lbl_80267840": "the u8 view is in another build branch (not MENU_COLOSSEUM_BATTLE_MAIN_ONLY); s32 reads use the s32 def",
    "lbl_802738B8": "a string past the table's end (OSReport), the pastend.py family",
    "lbl_802E4DB0": "walked as bytes, read as *(s32*)walk at +0: the record's s32 field",
    "lbl_802E4EB8": "a u8* macro view (menuPokemon.c); the reads are u16",
    "lbl_802E52C8": "the u8 view reads at +0x24C, past the table's 0x12C bytes: the pastend.py family",
    "lbl_802EEEC4": "a u8* base for *(s32*)(base + n * 4) reads",
    "lbl_80314350": "the u8 view is gs_gfx_range_800D3FA4.c's non-owner copy of gfxBegin; the PC links the owner's u32 copy",
    "item_ball_data": "address only (itemBallDataBiosGetPtr returns a pointer into the records)",
}


def struct_widths():
    """{struct name: set of scalar field widths} for `struct [DISC_STRUCT] Name { ... }` / `typedef struct ... } Name;`
    found anywhere in src and include (nested structs count by their own fields); "disc" for a struct that is
    big-endian on the PC (DISC_STRUCT: reads raw bytes correctly); None when a field's type is not known. The first
    definition of a name wins (local typedefs in different functions may differ: a guess-level view)."""
    bodies = {}
    for p in list((ROOT / "src").rglob("*.c")) + list((ROOT / "include").rglob("*.h")):
        t = strip_comments(p.read_text(encoding="utf-8", errors="replace"))
        for m in re.finditer(r"\bstruct\s+(DISC_STRUCT\s+)?(\w+)?\s*\{([^{}]*)\}\s*(\w+)?\s*;", t):
            for name in {m.group(2), m.group(4)} - {None}:
                bodies.setdefault(name, (bool(m.group(1)), m.group(3)))
    out = {}

    def widths(name, depth=0):
        if name in out or depth > 8:
            return out.get(name)
        disc, body = bodies[name]
        if disc:
            return "disc"
        ws = set()
        for field in body.split(";"):
            fm = re.match(r"\s*(?:const\s+|volatile\s+|struct\s+)*((?:unsigned\s+|signed\s+)?\w+)\s*(\**)\s*\w+", field)
            if not fm:
                continue
            ty, ptr = fm.group(1), fm.group(2)
            if ptr:
                ws.add(4)
            elif ty in GEN_W:
                ws.add(GEN_W[ty])
            elif ty in bodies:
                sub = widths(ty, depth + 1)
                if not isinstance(sub, set):
                    return None
                ws |= sub
            else:
                return None
        return ws

    for name in bodies:
        out[name] = widths(name)
    return out


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def branches(text):
    """{line: "pc" | "gc"} for lines inside a TARGET_PC conditional: "pc" in the branch only the PC compiles
    (`#ifdef TARGET_PC`, or the `#else` of `#ifndef TARGET_PC`), "gc" in the branch only the GameCube compiles. Nested
    conditionals are followed with a stack; the innermost TARGET_PC test wins."""
    out, stack = {}, []  # stack entries: None (an unrelated #if) or [polarity] (True: this branch is the PC's)
    for n, line in enumerate(text.split("\n"), 1):
        s = line.strip()
        if re.match(r"#\s*ifndef\s+TARGET_PC\b|#\s*if\s+!\s*defined\s*\(?\s*TARGET_PC\b", s):
            stack.append([False])
        elif re.match(r"#\s*ifdef\s+TARGET_PC\b|#\s*if\s+defined\s*\(?\s*TARGET_PC\b\s*\)?\s*$|#\s*if\s+TARGET_PC\b", s):
            stack.append([True])
        elif re.match(r"#\s*if", s):
            stack.append(None)
        elif re.match(r"#\s*else\b", s) and stack:
            if stack[-1] is not None:
                stack[-1][0] = not stack[-1][0]
        elif re.match(r"#\s*endif\b", s) and stack:
            stack.pop()
        else:
            for f in reversed(stack):
                if f is not None:
                    out[n] = "pc" if f[0] else "gc"
                    break
    return out


def line_of(text, pos):
    return text.count("\n", 0, pos) + 1


def all_zero(init):
    vals = re.findall(r"0x[0-9A-Fa-f]+|\d+\.?\d*(?:e[+-]?\d+)?|'[^']*'|\"[^\"]*\"", init)
    if not vals:
        return False
    for v in vals:
        if v.startswith(("'", '"')):
            return False
        try:
            if float(int(v, 16) if v.lower().startswith("0x") else float(v)) != 0:
                return False
        except ValueError:
            return False
    return True


def find_build_file(option, rel):
    """a PC build output: the --option path, else this checkout's, else the main checkout's (from a worktree)."""
    if option in sys.argv:
        return Path(sys.argv[sys.argv.index(option) + 1])
    for base in (ROOT, ROOT.parents[2] if ROOT.parent.name == "worktrees" else None):
        if base is not None and (base / rel).exists():
            return base / rel
    return None


def compiled_files(path):
    """repo-relative .c files the PC build compiles: the units in build-pc/firstlink/compiled.txt plus the .c files they
    #include (the split units include the big files with range defines). None when the list is not available."""
    if path is None:
        return None
    todo = [ln.strip() for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip().endswith(".c")]
    seen = set()
    while todo:
        f = todo.pop()
        if f in seen or not (ROOT / f).exists():
            continue
        seen.add(f)
        for inc in re.findall(r'^\s*#\s*include\s+"([^"]+\.c)"', (ROOT / f).read_text(encoding="utf-8", errors="replace"), re.M):
            for cand in (ROOT / inc, (ROOT / f).parent / inc):
                if cand.exists():
                    todo.append(cand.resolve().relative_to(ROOT.resolve()).as_posix())
                    break
    return seen


def read_generated(path):
    """{name: PC form}: ("raw", 1) raw big-endian bytes; ("bytes", 1) a byte table (strings, byte lists);
    ("typed", w) native elements of width w; ("record", {widths}) native records."""
    out = {}
    if path is None:
        return out
    for m in GEN_RE.finditer(path.read_text(encoding="utf-8", errors="replace")):
        head, fields, name, rest = m.group(1), m.group(2), m.group(3), m.group(0)
        if fields is not None:
            ws = {GEN_W.get(" ".join(f.split()[:-1]), 4) for f in fields.split(";") if f.strip()}
            out[name] = ("typed", ws.pop()) if len(ws) == 1 else ("record", ws)
            continue
        ty = " ".join(head.split())
        if ty in BYTE:
            out[name] = ("raw", 1) if "raw big-endian" in rest else ("bytes", 1)
        elif ty.endswith("*"):
            out[name] = ("typed", 8)  # a native pointer slot (8 bytes on the PC)
        elif ty in GEN_W:
            out[name] = ("typed", GEN_W[ty])
    return out


def read_fixed():
    """names that sit at their GameCube address as raw big-endian bytes (pcfixed.txt raw ranges)."""
    ranges = []
    p = ROOT / "tools" / "local" / "port" / "pcfixed.txt"
    if p.exists():
        for line in p.read_text(encoding="utf-8").splitlines():
            m = re.match(r"raw\s+(0x[0-9A-Fa-f]+)\s+(0x[0-9A-Fa-f]+)", line)
            if m:
                ranges.append((int(m.group(1), 16), int(m.group(2), 16)))
    out = set()
    for line in (ROOT / "config" / "GC6E01" / "symbols.txt").read_text(encoding="utf-8").splitlines():
        m = re.match(r"(lbl_[0-9A-F]{8}) = \.\w+:0x([0-9A-F]+);", line)
        if m and any(lo <= int(m.group(2), 16) < hi for lo, hi in ranges):
            out.add(m.group(1))
    return out


def disc_bases(text):
    """{position: label} of the labels a DISC_* accessor reads from: the first operand of its argument, after casts, `&`
    and parentheses (`DISC_U16(&lbl_X[i])`, `DISC_S16((s16*)(lbl_X + 4))`). Labels elsewhere in the argument (an index
    computed from another table) are ordinary native reads."""
    out = {}
    for m in DISC_RE.finditer(text):
        b = re.match(r"(?:\s*(?:\(\s*(?:const\s+|volatile\s+)*\w+\s*\**\s*\)|\(|&))*\s*(lbl_[0-9A-F]{8})\b", text[m.end():])
        if b:
            out[m.end() + b.start(1)] = b.group(1)
    return out


def main():
    show_all = "--all" in sys.argv
    gen_path = find_build_file("--generated", "build-pc/generated/pc_data_main.c")
    generated = read_generated(gen_path)
    comp_path = find_build_file("--compiled", "build-pc/firstlink/compiled.txt")
    compiled = compiled_files(comp_path)
    fixed = read_fixed()
    structs = struct_widths()
    defs, uses = {}, {}
    for base in SRC:
        for path in base.rglob("*.c"):
            raw = path.read_text(encoding="utf-8", errors="replace")
            text = strip_comments(raw)
            rel = path.relative_to(ROOT).as_posix()
            # a file the PC doesn't compile: its reads don't happen there, and its definitions are generated
            on_pc = compiled is None or rel in compiled
            branch = branches(text)
            for m in DEF_RE.finditer(text):
                typ, sym, init = m.group(1), m.group(2), m.group(4)
                ln = line_of(text, m.start(2))
                d = defs.setdefault(sym, {"type": typ, "where": f"{rel}:{ln}", "zero": all_zero(init),
                                          "handled": False, "gc_only": False})
                if branch.get(ln) == "pc":
                    d["handled"] = True
                elif branch.get(ln) == "gc" or not on_pc:
                    d["gc_only"] = True
            if not on_pc:
                continue
            bases ={p: s for p, s in disc_bases(text).items() if branch.get(line_of(text, p)) != "gc"}
            masked = list(text)  # the text with every DISC_* base label blanked, for the declarations' by-value test
            for pos, sym in bases.items():
                uses.setdefault(sym, []).append(("be", "disc", f"{rel}:{line_of(text, pos)}"))
                masked[pos:pos + len(sym)] = "disc_base___"
            # lines the PC compiles (GameCube-only branches blanked)
            masked = "\n".join("" if branch.get(n) == "gc" else ln
                               for n, ln in enumerate("".join(masked).split("\n"), 1))
            for rx, form_kind in ((DECL_RE, "decl"), (CAST_RE, "cast"), (STORE_RE, "store")):
                for m in rx.finditer(text):
                    sym, kind = m.group(2), form_kind
                    if m.start(2) in bases or branch.get(line_of(text, m.start(2))) == "gc":
                        continue  # read through a big-endian accessor (counted above), or GameCube-only code
                    if kind == "decl":
                        # a declaration only matters when the file uses the label outside extern lines; it reads the
                        # data at the declared width when it indexes an array declaration or uses a scalar by value
                        # (other uses take the address: "addr", a CHECK)
                        others = "\n".join(ln for ln in masked.split("\n") if sym in ln and not re.search(r"\bextern\b", ln)
                                           and not re.match(r"\s*(?:\w+\s+)*\w+\s*\**\s*" + sym + r"\s*(\[[^\]]*\]\s*)*=[^=]", ln))
                        if not others:
                            continue
                        is_array = re.match(r"\s*\[", text[m.end():])
                        byval = re.search(sym + r"\s*\[", others) if is_array else \
                            re.search(r"(?<![&\w])\s*" + sym + r"\b", others.replace("&" + sym, ""))
                        kind = "decl" if byval else "addr"
                    uses.setdefault(sym, []).append((m.group(1), kind, f"{rel}:{line_of(text, m.start(2))}"))
            for rx in (SDECL_RE, SCAST_RE):
                for m in rx.finditer(text):
                    sym, ty = m.group(2), m.group(1)
                    if ty in NOT_STRUCT or m.start(2) in bases or branch.get(line_of(text, m.start(2))) == "gc":
                        continue
                    if rx is SDECL_RE and not any(sym in ln and not re.search(r"\bextern\b", ln) for ln in masked.split("\n")):
                        continue
                    uses.setdefault(sym, []).append((ty, "struct", f"{rel}:{line_of(text, m.start(2))}"))

    report = {"BUG": [], "CHECK": [], "triaged": [], "ok": [], "handled": []}
    for sym, d in sorted(defs.items()):
        if d["zero"] and not show_all:
            continue
        us = uses.get(sym, [])
        if not us:
            continue
        # the PC storage
        if d["handled"]:
            report["handled"].append((sym, d, "defined under TARGET_PC", []))
            continue
        if sym in generated:
            form, w = generated[sym]
            src = "generated by pcdata.py"
        elif d["gc_only"] and sym in fixed:
            form, w, src = "raw", 1, "at its GameCube address (pcfixed.txt)"
        elif d["gc_only"] and generated:
            # not in the generated data: the PC defines it elsewhere (port / extern code), or nothing linked needs it
            report["handled"].append((sym, d, "not generated (defined by the port, or not linked)", []))
            continue
        elif d["gc_only"]:
            form, w = ("raw", 1) if WIDTH[d["type"]] == 1 else ("typed", WIDTH[d["type"]])
            src = "generated by pcdata.py (generated file not found: judged by the GameCube definition)"
        else:
            form, w = ("bytes", 1) if WIDTH[d["type"]] == 1 else ("typed", WIDTH[d["type"]])
            src = "compiled from this definition"
        bad, check = [], []
        native_widths = {WIDTH[t] for t, k, _ in us if k not in ("disc", "addr", "struct")}
        for t, k, where in us:
            if k == "addr" and WIDTH[t] == 1:
                continue  # a byte-array declaration used only for its address: "some bytes", no read width
            if k == "struct":
                sw = structs.get(t)
                if not isinstance(sw, set) or max(sw, default=1) == 1:
                    continue  # a DISC_STRUCT (big-endian on the PC), an unknown layout, or bytes only
                if form in ("raw", "bytes"):
                    bad.append((t, k, where, f"bytes in GameCube order read through struct {t} (fields {sorted(sw)} wide)"))
                elif form == "typed" and w > 1 and sw != {w}:
                    check.append((t, k, where, f"struct {t} (fields {sorted(sw)} wide) over width-{w} native elements"))
                continue
            if k == "disc":
                if form == "typed" and w > 1 or form == "record":
                    bad.append((t, k, where, "big-endian read of a table the PC stores in native order"))
                continue
            rw = WIDTH[t]
            if form in ("raw", "bytes"):
                if rw > 1:
                    (check if k == "addr" else bad).append((t, k, where, "native wide read of bytes in GameCube order"))
            elif form == "typed":
                if rw != w:
                    (bad if k in ("cast", "store", "decl") and rw > 1 else check).append(
                        (t, k, where, f"read at width {rw}, the PC stores width-{w} native elements"))
            elif form == "record":
                if rw not in w:
                    check.append((t, k, where, f"read at width {rw}, the PC record's fields are {sorted(w)} wide"))
        if not bad and len(native_widths) > 1 and form != "record":
            check.append(("-", "mixed", "-", f"read at several widths {sorted(native_widths)}: a copy then a read?"))
        kind = "BUG" if bad else "CHECK" if check else "ok"
        if kind != "ok" and sym in TRIAGED:
            report["triaged"].append((sym, d, TRIAGED[sym], bad + check))
            continue
        report[kind].append((sym, d, f"PC: {form}{'' if form == 'record' else ' width %d' % w}, {src}", bad + check))

    def show(kind, items):
        for sym, d, pc, rows in items:
            print(f"{kind} {sym}: GameCube {d['type']} at {d['where']}; {pc}")
            for t, k, where, why in rows:
                print(f"    {k} as {t} at {where}: {why}" if k != "mixed" else f"    {why}")

    print(f"generated data: {gen_path if gen_path else 'not found (pass --generated)'}")
    show("BUG", report["BUG"])
    show("CHECK", report["CHECK"])
    if show_all:
        show("triaged", report["triaged"])
        show("ok", report["ok"])
        for sym, d, pc, _ in report["handled"]:
            print(f"handled {sym}: {d['where']} ({pc})")
    print(f"\n{len(report['BUG'])} bug(s), {len(report['CHECK'])} to check, {len(report['triaged'])} triaged as correct, "
          f"{len(report['ok'])} ok, {len(report['handled'])} handled (a TARGET_PC definition, or not generated); "
          f"{len(defs)} initialised labels scanned")


if __name__ == "__main__":
    main()
