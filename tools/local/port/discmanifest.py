"""The disc check's reference list (OrrePort, 2026-11-02, for B to review; docs/port/disc-data-loading.md "The
disc check"): every file on the USA disc (game ID GC6E01) with its size and SHA-1, written to the untracked
build-pc/generated/pc_disc_manifest.c (marker line; never committed: generated from the disc). At start-up
port/src/pc_disc_check.c hashes the player's disc file by file and compares, so a bad dump or a modified disc is
named, not left to crash later. Names and hashes only: no game data.

The reference is the build machine's own image, found by its game ID (it must also match config/GC6E01/build.sha1's
main.dol and module SHA-1s, which the GameCube build verifies; checked here for main.dol).

Usage (repo root): python -I tools/local/port/discmanifest.py [--disc IMAGE] [--out build-pc/generated]
  (the image: --disc, else $ORRE_DISC_IMAGE, else the orig/*.iso whose game ID is GC6E01; none: an empty list, and
  the exe skips the check with a log line)
"""
import argparse
import glob
import hashlib
import os
import struct
from pathlib import Path

MARKER = "/* generated by tools/local/port/discmanifest.py from the disc image; not in version control */"


def find_disc(arg):
    for cand in [arg, os.environ.get("ORRE_DISC_IMAGE")] + sorted(glob.glob("orig/*.iso")):
        if cand and os.path.isfile(cand):
            with open(cand, "rb") as f:
                if f.read(6) == b"GC6E01":
                    return cand
    return None


def files_of(path):
    """[(entry number, path, offset, size)] from the disc's file table (as colo/disc.py reads it)"""
    f = open(path, "rb")

    def read(off, n):
        f.seek(off)
        return f.read(n)

    fo, fs = struct.unpack(">II", read(0x424, 8))
    fst = read(fo, fs)
    n = struct.unpack(">I", fst[8:12])[0]
    names = fst[n * 12:]
    out, ends = [], []
    for i in range(1, n):
        while ends and i >= ends[-1][0]:
            ends.pop()
        w0, a, b = struct.unpack(">III", fst[i * 12:i * 12 + 12])
        nm = names[w0 & 0xFFFFFF:names.index(b"\0", w0 & 0xFFFFFF)].decode("ascii", "replace")
        full = f"{ends[-1][1]}/{nm}" if ends else nm
        if w0 >> 24:
            ends.append((b, full))
        else:
            out.append((i, full, a, b))
    return f, read, n, out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--disc")
    ap.add_argument("--out", default="build-pc/generated")
    a = ap.parse_args()
    Path(a.out).mkdir(parents=True, exist_ok=True)
    disc = find_disc(a.disc)
    lines = [MARKER, "#include <stdint.h>", "",
             "typedef struct { const char* path; uint32_t size; uint8_t sha1[20]; } PcDiscFile;"]
    if disc is None:
        lines += ["const uint32_t pc_disc_fst_entries = 0;", "const uint32_t pc_disc_file_count = 0;",
                  "const PcDiscFile pc_disc_files[1] = {{0}};", 'const char pc_disc_manifest_id[] = "";']
        Path(a.out, "pc_disc_manifest.c").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("discmanifest: no GC6E01 image found: an empty list (the exe skips the disc check)")
        return
    f, read, entries, files = files_of(disc)
    # the disc's main.dol must be the one the GameCube build verifies (config/GC6E01/build.sha1)
    dol_off = struct.unpack(">I", read(0x420, 4))[0]
    h = read(dol_off, 0x100)
    offs, sizes = struct.unpack(">18I", h[0:72]), struct.unpack(">18I", h[144:216])
    dol_sha = hashlib.sha1(read(dol_off, max(o + z for o, z in zip(offs, sizes)))).hexdigest()
    want = next(l.split()[0] for l in open("config/GC6E01/build.sha1") if l.strip().endswith("main.dol"))
    if dol_sha != want:
        raise SystemExit(f"discmanifest: {disc}'s main.dol is {dol_sha}, not build.sha1's {want}: not a reference")
    ident = hashlib.sha1()
    rows = []
    for num, path, off, size in files:
        sha = hashlib.sha1(read(off, size)).digest()
        ident.update(f"{path}|{size}|{sha.hex()}\n".encode())
        rows.append(f'    {{"{path}", {size}u, {{{", ".join(f"0x{b:02x}" for b in sha)}}}}},')
    lines += [f"const uint32_t pc_disc_fst_entries = {entries}u; /* the file table's entries, the root and folders too */",
              f"const uint32_t pc_disc_file_count = {len(files)}u;", "const PcDiscFile pc_disc_files[] = {"] + rows + [
              "};", f'const char pc_disc_manifest_id[] = "{ident.hexdigest()}";']
    Path(a.out, "pc_disc_manifest.c").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"discmanifest: {len(files)} files ({entries} file table entries) from {os.path.basename(disc)}")


if __name__ == "__main__":
    main()
