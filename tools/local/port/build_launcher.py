r"""Build the portable folder's launchers, OrrePort.exe and "OrrePort Studio.exe" (Phase 4 step 4.1, 2026-11-21).

    python -I tools/local/port/build_launcher.py [--out build-pc/launcher] [--mingw C:/msys64/mingw64/bin]

One small C program (port/launcher/orre_launcher.c says what it does and why) compiled twice: plain for OrrePort.exe
(starts bin\orrecolo.exe) and with -DORRE_STUDIO for "OrrePort Studio.exe" (starts bin\orrestudio.exe). Each is
static (-static: no MinGW DLLs of its own, so it starts on a PC with nothing installed), a window program (-mwindows: no
console window flashes up), Unicode (-municode, wWinMain), with its manifest and version details (orre_launcher.rc).
Its message boxes' words are compiled in from port/ui/lang/<code>.txt ("launcher.*" lines, the six official languages):
this script writes them into <out>/launcher_text.h first, so a translation change needs a rebuild of the launchers.
port/tools/stage_bin.py copies them from --out into the OrrePort folder beside bin\.

Platforms: Windows only. Linux and macOS get a shell script / .app bundle instead (orre_launcher.c's notes).
"""
import argparse
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MAIN = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
SRC = os.path.join(MAIN, "port", "launcher")
LANG = os.path.join(MAIN, "port", "ui", "lang")
TARGETS = (("OrrePort.exe", []), ("OrrePort Studio.exe", ["-DORRE_STUDIO"]))
# The official languages compiled into the launchers (the project rules: English, German, French, Italian, Spanish, Japanese),
# English first: it is the fallback for a missing line
LANGUAGES = ("en", "de", "fr", "it", "es", "ja")
KEYS = ("missing", "start_failed", "no_folder")


def lang_lines(code):
    """The launcher.* lines of one translation file ("key = text", \\n for a new line; pc_text.cpp's format)."""
    out = {}
    path = os.path.join(LANG, code + ".txt")
    if os.path.isfile(path):
        for line in open(path, encoding="utf-8-sig"):
            if line.startswith("launcher.") and " = " in line:
                key, _, text = line.rstrip("\r\n").partition(" = ")
                out[key[len("launcher."):]] = text.replace("\\n", "\n")
    return out


def wide(s):
    """A C wide-string literal for s: plain ASCII as is, everything else as \\x escapes (each closed off by a new
    literal, so a following hex digit isn't read into it), so the header is plain ASCII whatever the compiler's charset."""
    parts, cur = [], ""
    for ch in s:
        if ch == "\n":
            cur += "\\n"
        elif ch in '"\\':
            cur += "\\" + ch
        elif 32 <= ord(ch) < 127:
            cur += ch
        else:
            parts.append(f'L"{cur}"') if cur else None
            parts.append(f'L"\\x{ord(ch):04x}"')
            cur = ""
    if cur or not parts:
        parts.append(f'L"{cur}"')
    return " ".join(parts)


def write_text_header(out):
    """launcher_text.h: the launchers' message lines in the official languages, read from port/ui/lang/*.txt (why they
    are compiled in: orre_launcher.c, "Words the player sees"). A language without a line takes English's."""
    en = lang_lines("en")
    missing = [k for k in KEYS if k not in en]
    if missing:
        sys.exit("port/ui/lang/en.txt lacks launcher." + ", launcher.".join(missing))
    rows = []
    for code in LANGUAGES:
        lines = lang_lines(code)
        rows.append("    {\"%s\", %s}," % (code, ", ".join(wide(lines.get(k, en[k])) for k in KEYS)))
    text = ("/* Generated by tools/local/port/build_launcher.py from port/ui/lang/<code>.txt (the launcher. keys); "
            "do not edit. */\n"
            "typedef struct LauncherText {\n    const char* code;\n" +
            "".join(f"    const wchar_t* {k};\n" for k in KEYS) + "} LauncherText;\n"
            "static const LauncherText kLauncherText[] = {\n" + "\n".join(rows) + "\n};\n")
    path = os.path.join(out, "launcher_text.h")
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    return path


def run(cmd, env):
    r = subprocess.run(cmd, env=env, capture_output=True, text=True)
    if r.returncode != 0 or r.stderr.strip():
        print(r.stdout + r.stderr)
    if r.returncode != 0:
        sys.exit(f"failed ({r.returncode}): {os.path.basename(cmd[0])}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(MAIN, "build-pc", "launcher"))
    ap.add_argument("--mingw", default="C:/msys64/mingw64/bin")
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    os.makedirs(out, exist_ok=True)
    env = dict(os.environ)
    env["PATH"] = a.mingw + os.pathsep + env.get("PATH", "")
    gcc, windres = os.path.join(a.mingw, "gcc.exe"), os.path.join(a.mingw, "windres.exe")
    write_text_header(out)  # a generated build file in --out, never in the repo
    for exe, defs in TARGETS:
        res = os.path.join(out, exe.replace(" ", "_").replace(".exe", ".res.o"))
        run([windres, "-I", SRC] + defs + [os.path.join(SRC, "orre_launcher.rc"), "-O", "coff", "-o", res], env)
        tmp = os.path.join(out, exe + ".new")
        run([gcc, "-O2", "-Wall", "-Wextra", "-municode", "-mwindows", "-static", "-I", out] + defs +
            [os.path.join(SRC, "orre_launcher.c"), res, "-o", tmp], env)
        os.replace(tmp, os.path.join(out, exe))
        print(f"built {os.path.join(out, exe)} ({os.path.getsize(os.path.join(out, exe)) // 1024} KB)")


if __name__ == "__main__":
    main()
