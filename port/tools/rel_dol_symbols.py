"""Generate the main.dol address table pc_rel.c needs to link REL modules on the PC (docs/port/rel-loading.md).

REL modules point into main.dol (pointers in their data to main.dol globals and functions, and their _prolog's
stores into main.dol globals). On the PC those symbols are the PC program's own, so OSLink needs each one's PC
address: this writes a C file with {GameCube address, &symbol + offset} for every main.dol address the given RELs
refer to, and pc_rel_resolve_table() for pc_rel_set_resolver. Symbols are declared by name only (extern char), so the
file compiles without the game's headers; the link then needs every listed symbol to exist in the PC program.

Output goes to build-pc/generated (it is derived from the disc's REL files: marker line, never committed).

Usage (pc-platform repo root):
  python -I port/tools/rel_dol_symbols.py <folder with the .rel files, searched recursively (e.g. extracted/)>
      [-o build-pc/generated/rel_dol_symbols.c]
Prints a summary: how many addresses, how many inside a symbol (address = symbol + offset; on the PC such an offset is
right only if that symbol's layout is the same as on the GameCube: listed for review).
"""
import argparse
import bisect
import glob
import os
import re
import struct
import sys

MARKER = "ORREPORT-GENERATED-" + "FROM-DISC"  # split so this tool file itself does not carry the marker


def dol_targets(path):
    r = open(path, "rb").read()
    u = lambda o: struct.unpack(">I", r[o:o + 4])[0]
    mid, imp, size = u(0), u(0x28), u(0x2C)
    out = set()
    for i in range(size // 8):
        module, off = u(imp + 8 * i), u(imp + 8 * i + 4)
        p = off
        while True:
            o, t, s, a = struct.unpack(">HBBI", r[p:p + 8])
            p += 8
            if t == 203:
                break
            if module == 0 and t not in (201, 202, 0):
                out.add(a)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dir")
    ap.add_argument("-o", default="build-pc/generated/rel_dol_symbols.c")
    args = ap.parse_args()

    syms = []
    for line in open("config/GC6E01/symbols.txt", encoding="utf-8"):
        m = re.match(r"^(\S+) = (\.\w+):0x([0-9A-F]+); // type:(\w+)(?: size:0x([0-9A-F]+))?", line)
        if m:
            syms.append((int(m.group(3), 16), m.group(1), m.group(2), int(m.group(5) or "0", 16)))
    syms.sort()
    starts = [s[0] for s in syms]

    targets = set()
    paths = sorted(set(glob.glob(os.path.join(args.dir, "**", "*.rel"), recursive=True)))
    for path in paths:
        targets |= dol_targets(path)

    rows, inside, missing = [], [], []
    for a in sorted(targets):
        i = bisect.bisect_right(starts, a) - 1
        if i < 0 or a >= syms[i][0] + max(syms[i][3], 1):
            missing.append(a)
            continue
        base, name, section, size = syms[i]
        rows.append((a, name, a - base, section))
        if a != base:
            inside.append((a, name, a - base))

    os.makedirs(os.path.dirname(args.o), exist_ok=True)
    with open(args.o, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"/* {MARKER}: generated by port/tools/rel_dol_symbols.py from the REL files' relocations and\n"
                " * config/GC6E01/symbols.txt; never commit. main.dol address -> PC address, for pc_rel.c's OSLink. */\n")
        f.write("#include <stddef.h>\n#include <stdint.h>\n\n")
        for name in sorted({r[1] for r in rows}):
            f.write(f"extern char {name};\n")
        f.write("\ntypedef struct { unsigned gc; char* pc; } RelDolSymbol;\n")
        f.write("static const RelDolSymbol s_table[] = {\n")
        for a, name, off, section in rows:
            f.write(f"    {{0x{a:08X}u, &{name} + 0x{off:X}}}, /* {section} */\n")
        f.write("};\n\n")
        f.write("unsigned pc_rel_resolve_table(unsigned gc) {\n"
                "    size_t lo = 0, hi = sizeof(s_table) / sizeof(s_table[0]);\n"
                "    while (lo < hi) {\n"
                "        size_t mid = (lo + hi) / 2;\n"
                "        if (s_table[mid].gc < gc) {\n"
                "            lo = mid + 1;\n"
                "        } else {\n"
                "            hi = mid;\n"
                "        }\n"
                "    }\n"
                "    if (lo < sizeof(s_table) / sizeof(s_table[0]) && s_table[lo].gc == gc) {\n"
                "        return (unsigned)(uintptr_t)s_table[lo].pc;\n"
                "    }\n"
                "    return 0;\n"
                "}\n")
    sections = {}
    for a, name, off, section in rows:
        sections[section] = sections.get(section, 0) + 1
    print(f"{len(paths)} modules; {len(targets)} main.dol addresses referenced: {len(rows)} mapped ({sections}), {len(missing)} not in "
          f"symbols.txt, {len(inside)} inside a symbol (offset != 0)")
    for a, name, off in inside[:20]:
        print(f"  0x{a:08X} = {name} + 0x{off:X}")
    for a in missing[:20]:
        print(f"  missing: 0x{a:08X}")
    print(f"wrote {args.o}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
