"""musyx_prefix.py: a second, renamed copy of the PC's MusyX library (the sound split prototype, 2026-11-16;
docs/port/sound-split.md).

Why: the sound split runs two MusyX instances side by side. The game's own one (liborre_musyx.a, unchanged) keeps the
console's 1x schedule and answers every "has this sound ended?"; a second copy, the audible one, renders the music at
its normal tempo for the speakers while the game runs faster. MusyX keeps all of its state in globals (voices, songs,
the mixer, the PC layer's device), so the cheapest way to get a second instance is to compile the same sources again
with every global name the library defines renamed to aud_<name>: a force-included header of #defines, generated
from the first library's own symbol table, so a new global in MusyX is picked up by the next build.

Two commands (port/CMakeLists.txt runs both):
  python -I musyx_prefix.py header <nm> <liborre_musyx.a> <out.h> [musyx_pc_alias.h]
      writes `#define <name> aud_<name>` for each global the library defines (compiler-made names skipped), and
      re-points the alias header's address names at the renamed globals;
  python -I musyx_prefix.py check <nm> <liborre_musyx_aud.a> <liborre_musyx.a>
      fails the build if the copy defines a global without the prefix (it would clash at link time) or still refers
      to one of the first library's globals (it would silently share the game instance's state: a macro elsewhere
      that hides a name from the header). Shared outside names (the C library, SDL, the game's two float constants
      lbl_8047D3B0 / lbl_8047D3C0, pc_ptr32_fail) are allowed: they hold no MusyX state.

Platforms: plain Python over binutils' nm; the same on Windows (MinGW), Linux and macOS (with GNU nm or llvm-nm;
macOS's own nm prints a leading underscore, which would need stripping: guess, unchecked).
"""
import subprocess
import sys

PREFIX = "aud_"


def nm_lines(nm, lib, *flags):
    r = subprocess.run([nm, *flags, lib], capture_output=True, text=True, check=True)
    return r.stdout.splitlines()


def defined_globals(nm, lib):
    names = set()
    for line in nm_lines(nm, lib, "-g", "--defined-only"):
        w = line.split()
        if len(w) == 3 and w[1] not in ("U", "w", "v"):  # defined (code, data, bss, read-only, common, weak)
            names.add(w[2])
    # compiler-made entries (MinGW's .refptr.X slots, __real@ / __xmm@ float constants) are COMDAT and renamed with
    # their target by the compiler itself; nothing to do for them
    return {n for n in names if not n.startswith((".", "__"))}


def undefined_names(nm, lib):
    out = set()
    for line in nm_lines(nm, lib, "-u"):
        w = line.split()
        if len(w) == 2 and w[0] == "U":
            out.add(w[1])
    return out


def alias_pairs(alias_header):
    """musyx_pc_alias.h's `#define <address name> <real name>` lines"""
    import re
    if not alias_header:
        return []
    text = open(alias_header, encoding="utf-8").read()
    return re.findall(r"^#define (\w+) (\w+)\b", text, re.M)


def cmd_header(nm, lib, out, alias_header=None):
    names = sorted(defined_globals(nm, lib))
    body = "".join(f"#define {n} {PREFIX}{n}\n" for n in names)
    # The address names musyx_pc_alias.h maps to a real name point straight at the renamed one too. Needed because a
    # few units define the real name as a macro over the address name (synthmacros.c: `#define synthInfo
    # (*(SynthInfo*)lbl_80434C50)`), which replaces this header's `synthInfo` and then reaches `synthInfo` again
    # through the alias, where the preprocessor stops expanding it (first build, 2026-11-16: "synthInfo undeclared").
    # This header is force-included after the alias header, so these win.
    for a, real in alias_pairs(alias_header):
        if real in names:
            body += f"#undef {a}\n#define {a} {PREFIX}{real}\n"
    text = ("/* generated by port/tools/musyx_prefix.py from liborre_musyx.a; not in version control.\n"
            " * The sound split's audible MusyX copy: every global of the game's MusyX library renamed (sound-split.md) */\n"
            "#ifndef ORRE_MUSYX_AUDIBLE_PREFIX_H\n#define ORRE_MUSYX_AUDIBLE_PREFIX_H\n" + body + "#endif\n")
    try:
        old = open(out, encoding="utf-8").read()
    except OSError:
        old = None
    if old != text:  # unchanged content keeps its time stamp, so the copy is not recompiled for nothing
        with open(out, "w", encoding="utf-8") as f:
            f.write(text)
    print(f"musyx_prefix: {len(names)} names -> {out}")


def cmd_check(nm, aud_lib, lib):
    primary = defined_globals(nm, lib)
    aud_defined = defined_globals(nm, aud_lib)
    bad_def = sorted(n for n in aud_defined if not n.startswith(PREFIX))
    bad_ref = sorted(n for n in undefined_names(nm, aud_lib) if n in primary)
    for n in bad_def:
        print(f"musyx_prefix check: the audible copy defines {n} without the {PREFIX} prefix", file=sys.stderr)
    for n in bad_ref:
        print(f"musyx_prefix check: the audible copy refers to the game instance's {n}", file=sys.stderr)
    if bad_def or bad_ref:
        sys.exit(1)
    print(f"musyx_prefix check: OK ({len(aud_defined)} globals, all prefixed; no reference to the game instance)")


if __name__ == "__main__":
    if len(sys.argv) in (5, 6) and sys.argv[1] == "header":
        cmd_header(sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5] if len(sys.argv) == 6 else None)
    elif len(sys.argv) == 5 and sys.argv[1] == "check":
        cmd_check(sys.argv[2], sys.argv[3], sys.argv[4])
    else:
        print(__doc__)
        sys.exit(2)
