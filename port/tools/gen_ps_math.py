"""Generate port/src/pc_mtx_ps.c: real PSMTX* / PSVEC* / PSQUAT* functions for the PC (docs/port/sdk-gaps.md).

Aurora's dolphin/mtx.h maps the paired-single names to its C versions with macros (`#define PSMTXConcat MTXConcat`,
then `#define MTXConcat C_MTXConcat`). That covers code that includes the header; game units that only declare the
functions themselves still need real symbols. For every `#define PS<name> <target>` in the header this writes a
function PS<name> that calls the C version, with the prototype of that C version.

Usage (repo root): python -I port/tools/gen_ps_math.py > port/src/pc_mtx_ps.c
"""
import re
import sys
from pathlib import Path

header = Path("extern/aurora/include/dolphin/mtx.h").read_text(encoding="utf-8")
text = re.sub(r"/\*.*?\*/", "", header, flags=re.S)
text = re.sub(r"//[^\n]*", "", text)

ps_targets = dict(re.findall(r"#define\s+(PS\w+)\s+(\w+)", text))
# routines rewritten to the console's rounding (port/src/pc_mtx_ps_exact.c, 2026-10-19) get no forwarder here
exact = set(re.findall(r"^\w[\w\s\*]*?\b(PS\w+)\s*\(", Path("port/src/pc_mtx_ps_exact.c").read_text(encoding="utf-8"),
                       re.M))
for name in exact:
    ps_targets.pop(name, None)
c_protos = {}
for ret, name, params in re.findall(r"^\s*([A-Za-z_][\w\s\*]*?)\s+(C_\w+)\s*\(([^;]*?)\)\s*;", text, re.M):
    c_protos[name] = (ret.strip(), " ".join(params.split()))


def c_name(ps):
    """PSMTXConcat -> C_MTXConcat (the macro chain ends there)."""
    return "C_" + ps[2:]


out = [
    "/*",
    " * pc_mtx_ps.c: real PSMTX* / PSVEC* / PSQUAT* functions for the PC, forwarding to Aurora's C versions",
    " * (docs/port/sdk-gaps.md). GENERATED by port/tools/gen_ps_math.py from extern/aurora/include/dolphin/mtx.h;",
    " * regenerate after an Aurora update. Aurora's header maps these names to the C versions with macros, which",
    " * covers code that includes it; game units that only declare the functions themselves need these symbols.",
    " */",
    "#include <dolphin/types.h>",
    "#include <dolphin/mtx.h>",
    "",
]
missing = []
for ps in sorted(ps_targets):
    target = c_name(ps)
    if target not in c_protos:
        missing.append(ps)
        continue
    ret, params = c_protos[target]
    names = []
    for p in params.split(","):
        p = p.strip()
        if not p or p == "void":
            continue
        m = re.search(r"(\w+)\s*(\[[^\]]*\])*\s*$", p)
        names.append(m.group(1))
    call = f"{target}({', '.join(names)})"
    body = f"return {call};" if ret != "void" else f"{call};"
    out.append(f"#undef {ps}")
    out.append(f"{ret} {ps}({params or 'void'}) {{ {body} }}")
    out.append("")
if missing:
    out.append("/* no C version found for: " + " ".join(missing) + " */")
sys.stdout.write("\n".join(out) + "\n")
